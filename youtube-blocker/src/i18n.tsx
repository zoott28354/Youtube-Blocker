type Translations = (typeof translations)[Lang];

const SUPPORTED_LANGS = Object.keys(translations) as Lang[];

function detectSystemLang(): Lang {
  const nav = navigator.language || "";
  const prefix = nav.split("-")[0].toLowerCase();
  if (SUPPORTED_LANGS.includes(prefix as Lang)) return prefix as Lang;
  return "en";
}

const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: Translations;
}>({ lang: "en", setLang: () => {}, t: translations.en });

export function LangProvider({ children }: { children: ReactNode }) {
  const stored = localStorage.getItem("lang") as Lang | null;
  const initial = stored && SUPPORTED_LANGS.includes(stored) ? stored : detectSystemLang();
  const [lang, setLangState] = useState<Lang>(initial);

  const setLang = (l: Lang) => {
    localStorage.setItem("lang", l);
    setLangState(l);
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t: translations[lang] }}>
      {children}
    </LangContext.Provider>
  );
}

export function useI18n() {
  return useContext(LangContext);
}
